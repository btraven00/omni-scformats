#!/usr/bin/env python3
"""Write plan.yaml from config/benchmark_testcases.json (copied verbatim
from crosscell@af3ea57 benchmark/config/). One DATA module per test case, so
module id == test_id (dots -> underscores: api 0.8 ids are [A-Za-z0-9_]).

    python3 scripts/gen_plan.py > plan.yaml
    python3 scripts/gen_plan.py --extended > plan-extended.yaml
"""
import json, sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
tc = json.loads((root / "config/benchmark_testcases.json").read_text())["test_cases"]


def data_modules(cases):
    for c in cases:
        mid = c["test_id"].replace(".", "_")
        yield (
            f"      - id: {mid}\n"
            f"        repository: *local_data\n"
            f"        parameters:\n"
            f"          - {{file: \"{c['file']}\"}}\n"
        )


def tools(names, timeout=600):
    for n in names:
        yield (
            f"      - id: {n}\n"
            f"        repository: *local_convert\n"
            f"        parameters:\n"
            f"          - {{tool: {n}, runs: 3, timeout: {timeout}}}\n"
        )


HEAD = """\
# GENERATED by scripts/gen_plan.py from config/benchmark_testcases.json.
# Edit the generator, not this file.
id: crosscell_repro
name: CrossCell benchmark, reproduced
description: >-
  Port of the CrossCell paper benchmark (github.com/biodancerwangzhi/crosscell,
  benchmark/, run_benchmark.py at a910b12): 5 converters x 2 directions over the
  same 55 test cases (42 Seurat RDS, 13 H5AD; Zenodo 10.5281/zenodo.18610876).
  Per case: 3 runs under GNU time + denet with obkit phases, median wall and
  ru_maxrss, then the output is checked for n_cells x n_genes. A failed
  conversion is a row, not a crash. Adds an scx arm, the binary alone, both
  directions (h5ad -> BPCells-backed .h5seurat, read by R; no .rds).
benchmarker: "btraven <ben.uzh@proton.me>"
version: "0.1.0"
api_version: "0.8.0"

software_backend: conda

software_environments:
  tools:
    name: all converters in one env (as crosscell's Dockerfile.benchmark)
    description: >-
      Latest R, Seurat, zellkonverter, anndataR, anndata from conda (the paper
      ran older ones, e.g. anndataR 1.0.0); convert2anndata, easySCFr from
      GitHub in post-deploy (scripts/run.sh). The
      crosscell (paper's prebuilt 0.1.0), scx and denet binaries are side-loaded
      via $CROSSCELL_BIN, $SCX_BIN, $DENET (see README).
    conda: envs/tools.yml
  readers:
    name: reference readers (checks) + the scx arm
    description: anndata, SeuratObject, BPCells, rhdf5; scx CLI via $SCX_BIN
    conda: envs/readers.yml
  py:
    name: python (staging, summary)
    conda: envs/py.yml

local_data: &local_data {url: ".", commit: HEAD, entrypoint: data}
local_convert: &local_convert {url: ".", commit: HEAD, entrypoint: convert}
local_validate: &local_validate {url: ".", commit: HEAD, entrypoint: validate}

stages:
  # Stage the inputs: hardlink out of $CROSSCELL_DATA (scripts/fetch.sh) and
  # check sha256 against the Zenodo manifest.
  - id: RDS
    outputs:
      - {id: rds, path: "{module.id}.rds"}
    modules:
"""

MID = """
  - id: H5AD
    outputs:
      - {id: h5ad, path: "{module.id}.h5ad"}
    modules:
"""

TAIL_TMPL = """
  # Conversion, measured: GNU time (the paper's ru_maxrss) around denet, plus
  # obkit phase anchors (load/read/convert/write) in every R step. Commands are
  # crosscell's run_benchmark.py cmd_*, phase-wrapped. A tool that fails or
  # times out writes an empty output and status=failed: failure is data.
  - id: TO_H5AD
    inputs: [rds]
    outputs:
      - {id: out_h5ad, path: "{module.id}.h5ad"}
      - {id: perf, path: "{module.id}.perf.json"}
    modules:
%s
  # Ends in a file R reads as Seurat data. The original tools write .rds; scx
  # writes .h5seurat (BPCells-packed counts + meta.data), since .rds is not an
  # interchange format (scx docs/rds-write.md). The declared .seurat is a
  # symlink to the file the tool wrote; CHECK_SEURAT reads that with R.
  - id: TO_SEURAT
    inputs: [h5ad]
    outputs:
      - {id: out_seurat, path: "{module.id}.seurat"}
      - {id: perf, path: "{module.id}.perf.json"}
    modules:
%s
  # Fidelity check (the original checked n_cells x n_genes only). Input and
  # output are read by their format's own reader (anndata; readRDS +
  # SeuratObject; rhdf5 + BPCells for .h5seurat) into a neutral snapshot and
  # compared property by property: names, obs/var columns (type class, values,
  # NA), every matrix (exact if integer-valued, else rtol 1e-6).
  # `scx diff --json` is recorded alongside as a cross-check, never the judge.
  - id: CHECK_H5AD
    inputs: [out_h5ad, rds]
    outputs:
      - {id: check, path: "{module.id}.check.json"}
    modules:
      - {id: dims_h5ad, software_environment: readers, repository: *local_validate}

  - id: CHECK_SEURAT
    inputs: [out_seurat, h5ad]
    outputs:
      - {id: check, path: "{module.id}.check.json"}
    modules:
      - {id: dims_seurat, software_environment: readers, repository: *local_validate}

  # Global fan-in: one table, one row per (test case, tool).
  # The paper's own matrix fidelity, as published: per RDS case, every tool's
  # h5ad X vs crosscell's (by position, 7 metrics). Reported beside ours.
  - id: PAPER_FIDELITY
    gather:
      - from: out_h5ad
        group_by: RDS
    outputs:
      - {id: paper_fidelity, path: "{RDS}.paper_fidelity.json"}
    modules:
      - id: compute_fidelity
        software_environment: tools
        repository: {url: ".", commit: HEAD, entrypoint: paper_fidelity}

  - id: SUMMARY
    gather:
      - from: perf
      - from: check
      - from: paper_fidelity
    outputs:
      - {id: results_tsv, path: "results.tsv"}
      - {id: tables_md, path: "tables.md"}
      - {id: tools_png, path: "tools.png"}
      - {id: tools_svg, path: "tools.svg"}
      - {id: phases_png, path: "phases.png"}
      - {id: phases_svg, path: "phases.svg"}
      - {id: fig3_png, path: "fig3.png"}
      - {id: fig3_svg, path: "fig3.svg"}
    modules:
      - id: tables
        software_environment: py
        repository: {url: ".", commit: HEAD, entrypoint: summary}
"""


EXT_SUMMARY = """  - id: SUMMARY
    gather:
      - from: perf
      - from: check
    outputs:
      - {id: results_tsv, path: "results.tsv"}
      - {id: tables_md, path: "tables.md"}
      - {id: ladder_png, path: "ladder.png"}
    modules:
      - id: tables
        software_environment: py
        repository: {url: ".", commit: HEAD, entrypoint: summary}
"""


def with_env(blocks, env):
    # The side-loaded binaries (scx, scConvert) need only python: `readers`.
    return "".join(b.replace("        repository:", f"        software_environment: {'readers' if ('- id: scx' in b or '- id: scConvert' in b) else env}\n        repository:", 1) for b in blocks)


# The paper's type-fidelity object (modules/typetest.R), as one more RDS case.
TYPE_TEST = """      - id: type_test
        name: "CrossCell type-fidelity object (50 cells, 5 typed columns)"
        software_environment: tools
        repository: {url: ".", commit: HEAD, entrypoint: typetest}
"""

R2H = ["crosscell", "zellkonverter", "anndataR", "convert2anndata", "easySCF", "scx"]
H2R = ["crosscell", "zellkonverter", "anndataR", "scx", "scConvert"]

if sys.argv[1:] == ["--extended"]:
    # plan-extended.yaml (extended/PLAN.md): the drawn CELLxGENE datasets and the ladder,
    # inputs built by scripts/build_extended.py; same stages minus the paper-only ones.
    ext = json.loads((root / "config/extended.json").read_text())
    rds, h5 = [], []  # module ids get _rds / _h5ad: results are keyed by (test_id, tool)
    n = {}
    for d in ext["datasets"]:
        n[d["bin"]] = n.get(d["bin"], 0) + 1
        name = f"ext_{d['bin']}{n[d['bin']]}"
        h5.append({"test_id": f"{name}_h5ad", "file": f"{name}.h5ad"})
        if d["rds"]:
            rds.append({"test_id": f"{name}_rds", "file": f"{name}.rds"})
    for r in ext["ladder"]["rungs"]:
        name = f"ladder_{r['rung']}"
        h5.append({"test_id": f"{name}_h5ad", "file": f"{name}.h5ad"})
        if r["rds"]:
            rds.append({"test_id": f"{name}_rds", "file": f"{name}.rds"})
    head = (HEAD.replace("id: crosscell_repro", "id: crosscell_extended")
            .replace("name: CrossCell benchmark, reproduced", "name: CrossCell benchmark, extended")
            .replace("# GENERATED by scripts/gen_plan.py from config/benchmark_testcases.json.",
                     "# GENERATED by scripts/gen_plan.py --extended from config/extended.json (extended/PLAN.md)."))
    tail = TAIL_TMPL[: TAIL_TMPL.index("  # Global fan-in")] + EXT_SUMMARY
    print(head + with_env(data_modules(rds), "py") + MID + with_env(data_modules(h5), "py")
          + tail % (with_env(tools(R2H, 3600), "tools"), with_env(tools(H2R, 3600), "tools")), end="")
    sys.exit()

print(HEAD + with_env(data_modules(tc["rds_to_h5ad"]), "py") + TYPE_TEST
      + MID + with_env(data_modules(tc["h5ad_to_rds"]), "py")
      + TAIL_TMPL % (with_env(tools(R2H), "tools"), with_env(tools(H2R), "tools")), end="")
