#!/usr/bin/env python3
"""Write benchmark.yaml from config/benchmark_testcases.json (copied verbatim
from crosscell@af3ea57 benchmark/config/). One DATA module per test case, so
module id == test_id (dots -> underscores: api 0.8 ids are [A-Za-z0-9_]).

    python3 scripts/gen_plan.py > benchmark.yaml
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
tc = json.loads((root / "config/benchmark_testcases.json").read_text())["test_cases"]


def data_modules(cases):
    for c in cases:
        mid = c["test_id"].replace(".", "_")
        yield (
            f"      - id: {mid}\n"
            f"        repository: *local_data\n"
            f"        parameters:\n"
            f"          - {{file: \"{c['file']}\", n_cells: {c['n_cells']}, n_genes: {c['n_genes']}}}\n"
        )


def tools(names):
    for n in names:
        yield (
            f"      - id: {n}\n"
            f"        repository: *local_convert\n"
            f"        parameters:\n"
            f"          - {{tool: {n}, runs: 3, timeout: 600}}\n"
        )


HEAD = """\
# GENERATED by scripts/gen_plan.py from config/benchmark_testcases.json.
# Edit the generator, not this file.
id: crosscell_repro
name: CrossCell benchmark, reproduced
description: >-
  Port of the CrossCell paper benchmark (github.com/biodancerwangzhi/crosscell,
  benchmark/, run_benchmark.py at a910b12): 5 converters x 2 directions over the
  same 55 test cases (42 Seurat RDS, 13 H5AD; Zenodo 10.5281/zenodo.18610876).
  Per case: 3 runs under GNU time + denet with obkit phases, median wall and
  ru_maxrss, then the output is checked for n_cells x n_genes. A failed
  conversion is a row, not a crash. Adds scx arms (rds -> h5ad; h5ad -> Seurat
  via picklerick or .bpcells).
benchmarker: "btraven <ben.uzh@proton.me>"
version: "0.1.0"
api_version: "0.8.0"

software_backend: conda

software_environments:
  tools:
    name: all converters in one env (as crosscell's Dockerfile.benchmark)
    description: >-
      R 4.5 + zellkonverter 1.20.1 + anndataR 1.0.0 + anndata 0.12.9 from conda;
      Seurat 5.4.0, convert2anndata, easySCFr/easySCFpy in post-deploy. The
      crosscell (paper's prebuilt 0.1.0), scx and denet binaries are side-loaded
      via $CROSSCELL_BIN, $SCX_BIN, $DENET (see README).
    conda: envs/tools.yml
  scx:
    name: scx routes into Seurat
    description: picklerick 0.5.0 + BPCells + SeuratObject (Bioc 3.22 generation)
    conda: envs/scx.yml
  py:
    name: python (staging, summary)
    conda: envs/py.yml

local_data: &local_data {url: ".", commit: HEAD, entrypoint: data}
local_convert: &local_convert {url: ".", commit: HEAD, entrypoint: convert}
local_validate: &local_validate {url: ".", commit: HEAD, entrypoint: validate}

stages:
  # Stage the inputs: hardlink out of $CROSSCELL_DATA (scripts/fetch.sh) and
  # check sha256 against the Zenodo manifest. `*_expected` carries the test
  # matrix's n_cells x n_genes, which VALIDATE checks the output against.
  # Two expected ids, not one shared `expected`: ob 0.7.0.post10 binds a shared
  # id to its first-declared producer only (010 §3.1 says alternatives), and
  # rejects CHECK_SEURAT. Merge back once fixed.
  - id: RDS
    outputs:
      - {id: rds, path: "{module.id}.rds"}
      - {id: rds_expected, path: "{module.id}.expected.json"}
    modules:
"""

MID = """
  - id: H5AD
    outputs:
      - {id: h5ad, path: "{module.id}.h5ad"}
      - {id: h5ad_expected, path: "{module.id}.expected.json"}
    modules:
"""

TAIL_TMPL = """
  # Conversion, measured: GNU time (the paper's ru_maxrss) around denet, plus
  # obkit phase anchors (load/read/convert/write) in every R step. Commands are
  # crosscell's run_benchmark.py cmd_*, phase-wrapped. A tool that fails or
  # times out writes an empty output and status=failed: failure is data.
  - id: TO_H5AD
    inputs: [rds]
    outputs:
      - {id: out_h5ad, path: "{module.id}.h5ad"}
      - {id: perf, path: "{module.id}.perf.json"}
    modules:
%s
  # Ends in a Seurat object, saved by R. scx does not write .rds (docs/
  # rds-write.md): its arms build the object in R (picklerick, or BPCells on
  # scx's .bpcells) and saveRDS there. Phases separate object from write.
  - id: TO_SEURAT
    inputs: [h5ad]
    outputs:
      - {id: out_seurat, path: "{module.id}.rds"}
      - {id: perf, path: "{module.id}.perf.json"}
    modules:
%s
  # Output check, as crosscell's validate_output.py: open the file with the
  # format's reference reader (anndata / readRDS) and compare n_cells x n_genes.
  - id: CHECK_H5AD
    inputs: [out_h5ad, rds_expected]
    outputs:
      - {id: check, path: "{module.id}.check.json"}
    modules:
      - {id: dims_h5ad, software_environment: tools, repository: *local_validate}

  - id: CHECK_SEURAT
    inputs: [out_seurat, h5ad_expected]
    outputs:
      - {id: check, path: "{module.id}.check.json"}
    modules:
      - {id: dims_seurat, software_environment: tools, repository: *local_validate}

  # Global fan-in: one table, one row per (test case, tool).
  - id: SUMMARY
    gather:
      - from: perf
      - from: check
    outputs:
      - {id: results_tsv, path: "results.tsv"}
      - {id: pass_rates_md, path: "pass_rates.md"}
    modules:
      - id: tables
        software_environment: py
        repository: {url: ".", commit: HEAD, entrypoint: summary}
"""


def with_env(blocks, env):
    # scx arms run in their own env (envs/scx.yml): the Bioconductor generations differ.
    return "".join(b.replace("        repository:", f"        software_environment: {'scx' if '- id: scx' in b else env}\n        repository:", 1) for b in blocks)


print(HEAD + with_env(data_modules(tc["rds_to_h5ad"]), "py")
      + MID + with_env(data_modules(tc["h5ad_to_rds"]), "py")
      + TAIL_TMPL % (with_env(tools(["crosscell", "zellkonverter", "anndataR", "convert2anndata", "easySCF", "scx"]), "tools"),
                     with_env(tools(["crosscell", "zellkonverter", "anndataR", "scx_picklerick", "scx_bpcells"]), "tools")), end="")
